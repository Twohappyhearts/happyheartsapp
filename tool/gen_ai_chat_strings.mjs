// Generates lib/presentation/ai_chat/ai_chat_strings.dart from the dashboard's
// patient AI chat texts, so the native chat says exactly what the web chat says.
//
//   node --experimental-strip-types tool/gen_ai_chat_strings.mjs [../happyheartsdash]
//   dart format lib/presentation/ai_chat/ai_chat_strings.dart
//
// Sources (happyheartsdash/src/lib): i18n/patient.ts (chat texts), agent-consent.ts
// (AI notice), agent-fixed-replies.ts (fixed safety replies), languages.ts.
// Needs Node 22.6+ (TypeScript type stripping). Run it again after those files change.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dashRoot = path.resolve(process.argv[2] ?? path.join(appRoot, '..', 'happyheartsdash'));
const lib = path.join(dashRoot, 'src', 'lib');
const out = path.join(appRoot, 'lib', 'presentation', 'ai_chat', 'ai_chat_strings.dart');

// Copy the four files to a temp folder with Node-resolvable imports.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-chat-strings-'));
const copy = (from, to, fix) => {
  let src = fs.readFileSync(path.join(lib, from), 'utf8');
  for (const [a, b] of fix) src = src.split(a).join(b);
  fs.writeFileSync(path.join(tmp, to), src);
};
copy('languages.ts', 'languages.ts', []);
copy('i18n/patient.ts', 'patient.ts', [["'@/lib/languages'", "'./languages.ts'"]]);
copy('agent-fixed-replies.ts', 'agent-fixed-replies.ts', [["'./languages'", "'./languages.ts'"]]);
copy('agent-consent.ts', 'agent-consent.ts', [
  ["'./agent-fixed-replies'", "'./agent-fixed-replies.ts'"],
  ["'./languages'", "'./languages.ts'"],
]);

const load = (f) => import(pathToFileURL(path.join(tmp, f)).href);
const { LANGUAGES, LANGUAGE_NAMES } = await load('languages.ts');
const { PATIENT_TEXT } = await load('patient.ts');
const { AI_NOTICE, AI_NOTICE_VERSION } = await load('agent-consent.ts');
const { FIXED_REPLIES_BY_LANGUAGE, CARETEAM_SITUATIONS } = await load('agent-fixed-replies.ts');

// ---- Dart helpers
const str = (s) =>
  "'" +
  String(s)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\n/g, '\\n') +
  "'";
/** A one-argument text function as a Dart closure: fn('\u0000') → '…$a…'. */
const fn1 = (f, arg = 'a') => {
  const marker = '\u0000';
  const s = f(marker);
  const parts = s.split(marker).map((p) => str(p).slice(1, -1));
  return `(${arg}) => '${parts.join('$' + arg)}'`;
};

const KEYS_PLAIN = [
  'openFromApp', 'signInAgain', 'newConversation', 'yourConversations', 'history', 'backToChat', 'newChat',
  'retry', 'noConversations', 'yesterday', 'deleteTitle', 'cancel', 'delete', 'deleting', 'listError',
  'openError', 'deleteError', 'emptyTitle', 'emptySubtitle', 'placeholder', 'send', 'stop', 'thinking',
  'lookingUp', 'writingAnswer', 'waitHint', 'chatError', 'openSourceError', 'edit', 'previousVersion',
  'nextVersion', 'versionFailed', 'copy', 'editingMessage',
];
const KEYS_FN = ['deleteConversation', 'deleteBody', 'call'];

// Every key of the TS interface must be handled here (sources and suggestions are special).
const handled = new Set([...KEYS_PLAIN, ...KEYS_FN, 'sources', 'suggestions']);
const missing = Object.keys(PATIENT_TEXT.en).filter((k) => !handled.has(k));
if (missing.length) throw new Error(`patient.ts has keys this generator does not know: ${missing.join(', ')}`);

const dartName = (lang) => lang.replace(/-(\w)/g, (_m, c) => c.toUpperCase()); // zh-Hans → zhHans

/** "n sources" per language, from the TS function sampled at 1..30. */
function sourcesFn(f) {
  // Group n by the text with the number replaced, so plural rules become Dart conditions.
  const forms = [];
  for (let n = 1; n <= 30; n++) {
    const s = f(n).split(String(n)).join('\u0000');
    const last = forms[forms.length - 1];
    if (last && last.text === s) last.to = n;
    else forms.push({ from: n, to: n, text: s });
  }
  const tpl = (t) => `'${t.split('\u0000').map((p) => str(p).slice(1, -1)).join('$n')}'`;
  if (forms.length === 1) return `(n) => ${tpl(forms[0].text)}`;
  const branches = forms.slice(0, -1).map((g) => (g.from === g.to ? `n == ${g.from}` : `n <= ${g.to}`) + ` ? ${tpl(g.text)} : `);
  return `(n) => ${branches.join('')}${tpl(forms[forms.length - 1].text)}`;
}

let dart = `// GENERATED by tool/gen_ai_chat_strings.mjs from the dashboard
// (src/lib/i18n/patient.ts, agent-consent.ts, agent-fixed-replies.ts). Do not edit by hand:
// change the dashboard files and run
//   node --experimental-strip-types tool/gen_ai_chat_strings.mjs
//   dart format lib/presentation/ai_chat/ai_chat_strings.dart
//
// Texts of the native AI chat in the app's eight languages, word for word the same as the
// web chat (/m/assistant). Every non-English text is a machine translation, pending
// research-team review.
// ignore_for_file: lines_longer_than_80_chars

/// Texts of the AI chat screen.
class AiChatStrings {
${KEYS_PLAIN.map((k) => `  final String ${k};`).join('\n')}
  final String Function(String title) deleteConversation;
  final String Function(String title) deleteBody;
  final String Function(String number) call;
  final String Function(int n) sources;

  /// General pregnancy / postpartum questions shown on an empty chat.
  final List<String> suggestions;

  const AiChatStrings({
${[...KEYS_PLAIN, ...KEYS_FN, 'sources', 'suggestions'].map((k) => `    required this.${k},`).join('\n')}
  });

  /// Texts for an app language code (en, es, vi, ko, zh-Hans, zh-Hant, fa, ar); else English.
  static AiChatStrings of(String code) => _byLanguage[code] ?? _en;
}

/// The AI notice a patient accepts before the first message (server version ${AI_NOTICE_VERSION}).
class AiNoticeStrings {
  final String title;

  /// The research team's disclaimer around its "Terms of Use" link: before, link, after.
  final String disclaimerBefore;
  final String disclaimerLink;
  final String disclaimerAfter;

  /// Under a translated disclaimer: the English wording is the official one ('' in English).
  final String officialNote;
  final List<String> points;
  final String agree;
  final String continueLabel;
  final String language;
  final String saveError;

  const AiNoticeStrings({
    required this.title,
    required this.disclaimerBefore,
    required this.disclaimerLink,
    required this.disclaimerAfter,
    required this.officialNote,
    required this.points,
    required this.agree,
    required this.continueLabel,
    required this.language,
    required this.saveError,
  });

  static AiNoticeStrings of(String code) => aiNotice[code] ?? aiNotice['en']!;
}

/// Languages of the app, in picker order.
const List<String> aiChatLanguages = [${LANGUAGES.map(str).join(', ')}];

/// Native name of each language (language picker).
const Map<String, String> aiChatLanguageNative = {
${LANGUAGES.map((l) => `  ${str(l)}: ${str(LANGUAGE_NAMES[l].native)},`).join('\n')}
};

/// Situations of the fixed safety replies (the care-team offer of older replies
/// used the same names).
const List<String> careteamSituations = [${CARETEAM_SITUATIONS.map(str).join(', ')}];

/// Fixed safety replies (rules 1 and 2), by language then situation.
const Map<String, Map<String, String>> fixedReplies = {
${LANGUAGES.map((l) => `  ${str(l)}: {\n${CARETEAM_SITUATIONS.map((s) => `    ${str(s)}: ${str(FIXED_REPLIES_BY_LANGUAGE[l][s])},`).join('\n')}\n  },`).join('\n')}
};

`;

for (const lang of LANGUAGES) {
  const t = PATIENT_TEXT[lang];
  // Not const: the texts with a number or a name are functions.
  dart += `final _${dartName(lang)} = AiChatStrings(\n`;
  for (const k of KEYS_PLAIN) dart += `  ${k}: ${str(t[k])},\n`;
  dart += `  deleteConversation: ${fn1(t.deleteConversation, 'title')},\n`;
  dart += `  deleteBody: ${fn1(t.deleteBody, 'title')},\n`;
  dart += `  call: ${fn1(t.call, 'number')},\n`;
  dart += `  sources: ${sourcesFn(t.sources)},\n`;
  dart += `  suggestions: [${t.suggestions.map(str).join(', ')}],\n`;
  dart += `);\n\n`;
}
dart += `final Map<String, AiChatStrings> _byLanguage = {\n${LANGUAGES.map((l) => `  ${str(l)}: _${dartName(l)},`).join('\n')}\n};\n\n`;

dart += `const Map<String, AiNoticeStrings> aiNotice = {\n`;
for (const lang of LANGUAGES) {
  const n = AI_NOTICE[lang];
  dart += `  ${str(lang)}: AiNoticeStrings(
    title: ${str(n.title)},
    disclaimerBefore: ${str(n.disclaimer[0])},
    disclaimerLink: ${str(n.disclaimer[1])},
    disclaimerAfter: ${str(n.disclaimer[2])},
    officialNote: ${str(n.officialNote)},
    points: [${n.points.map(str).join(', ')}],
    agree: ${str(n.agree)},
    continueLabel: ${str(n.continue)},
    language: ${str(n.language)},
    saveError: ${str(n.saveError)},
  ),\n`;
}
dart += `};\n`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, dart);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`Wrote ${path.relative(appRoot, out)}`);
